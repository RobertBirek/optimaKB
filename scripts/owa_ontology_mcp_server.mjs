function normalize(value) { return String(value || '').toLowerCase().replace(/\s+/g, ' ').trim(); }

function matchesSearch(row, query) {
  if (!query) return true;
  const terms = normalize(query).split(/\s+/).filter(Boolean);
  if (!terms.length) return true;
  const searchText = Object.values(row).map((v) => normalize(String(v ?? ''))).join(' ');
  for (const term of terms) {
    if (!searchText.includes(term)) return false;
  }
  return true;
}

function writeMessage(message) {
  const payload = JSON.stringify(message);
  process.stdout.write(`Content-Length: ${Buffer.byteLength(payload, 'utf8')}\r\n\r\n${payload}`);
}

function readJsonRpcRequest(buffer) {
  const headerEnd = buffer.indexOf('\r\n\r\n');
  if (headerEnd === -1) return null;
  const header = buffer.slice(0, headerEnd).toString('utf8');
  const match = header.match(/Content-Length:\s*(\d+)/i);
  if (!match) return null;
  const length = Number(match[1]);
  if (length > MAX_FRAME_BYTES) return null;
  const total = headerEnd + 4 + length;
  if (buffer.length < total) return null;
  try {
    const body = buffer.slice(headerEnd + 4, total).toString('utf8');
    const request = JSON.parse(body);
    return { request, consumed: total };
  } catch { return null; }
}

function success(id, result) { return { jsonrpc: '2.0', id, result }; }

function entitySummary(row) {
  return { id: row.id, canonicalName: row.canonicalName || row.name, verificationStatus: row.verificationStatus, confidenceLevel: row.confidenceLevel, businessDomain: row.businessDomain, mainTable: row.mainTable, ontologyId: row.ontologyId };
}

function entityFull(row) {
  const entity = entitySummary(row);
  entity.description = row.description || '';
  entity.mcpReadTools = (row.mcpReadTools || '').split(';').map((s) => s.trim()).filter(Boolean);
  entity.mcpWriteTools = (row.mcpWriteTools || '').split(';').map((s) => s.trim()).filter(Boolean);
  entity.aliases = (row.aliases || '').split(';').map((s) => s.trim()).filter(Boolean);
  entity.summary = row.summary || '';
  entity.fields = ontologyFields.filter((f) => f.entityRefId === row.id).map((f) => ({ name: f.name, mssqlColumn: f.mssqlColumn, mcpField: f.mcpField, sqlType: f.sqlType, nullable: f.nullable, keyRole: f.keyRole, mappingStatus: f.mappingStatus, description: f.description }));
  entity.relations = ontologyRelations.filter((r) => r.sourceEntityRefId === row.id).map((r) => ({ predicate: r.predicate, targetEntityRefId: r.targetEntityRefId, cardinality: r.cardinality, relationType: r.relationType, joinCondition: r.joinCondition, status: r.status }));
  entity.workflows = workflowPatterns.filter((w) => w.sourceEntityRefId === row.id).map((w) => ({ name: w.name, mcpTool: w.mcpTool, mode: w.mode, status: w.status, summary: w.summary }));
  return entity;
}

function findEntity(idOrName) {
  const search = normalize(idOrName);
  const exactById = ontologyEntities.find((e) => e.id === idOrName);
  if (exactById) return exactById;
  const exactByName = ontologyEntities.find((e) => normalize(e.name) === search || normalize(e.canonicalName) === search);
  if (exactByName) return exactByName;
  const searchTokens = search.split(/[^a-z0-9_]+/).filter(Boolean);
  if (!searchTokens.length) return null;
  let best = null, bestScore = -1;
  for (const e of ontologyEntities) {
    const entityText = normalize(e.name + ' ' + (e.canonicalName || ''));
    let matchCount = 0, exactWordBonus = 0;
    const words = entityText.split(/[^a-z0-9_]+/).filter(Boolean);
    for (const token of searchTokens) {
      if (entityText.includes(token)) { matchCount += 1; if (words.some((w) => w === token)) exactWordBonus += 1; }
    }
    if (matchCount === searchTokens.length) {
      const score = matchCount * 10 + exactWordBonus * 5 + (1 / Math.max(1, entityText.length));
      if (score > bestScore) { bestScore = score; best = e; }
    }
  }
  return best;
}

async function httpPost(url, headers, body) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 30000);
  try {
    const response = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(body), signal: controller.signal });
    const text = await response.text();
    try { return JSON.parse(text); } catch { return text; }
  } finally { clearTimeout(timeout); }
}

