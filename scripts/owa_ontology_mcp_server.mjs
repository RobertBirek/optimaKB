function loadCsv(fileName) {
  const filePath = path.join(CSV_DIR, fileName);
  if (!fs.existsSync(filePath)) return [];
  const data = fs.readFileSync(filePath, 'utf8').replace(/\r/g, '');
  const rows = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < data.length; i += 1) {
    const ch = data[i];
    current += ch;
    if (ch === '"') {
      if (inQuotes && data[i + 1] === '"') { current += data[i + 1]; i += 1; }
      else { inQuotes = !inQuotes; }
    } else if (ch === '\n' && !inQuotes) { rows.push(current.slice(0, -1)); current = ''; }
  }
  if (current) rows.push(current);
  if (rows.length < 2) return [];
  const headers = parseCsvLine(rows[0]);
  return rows.slice(1).map((line) => {
    const values = parseCsvLine(line);
    const row = {};
    headers.forEach((header, index) => { row[header] = values[index] ?? ''; });
    return row;
  });
}

function parseCsvLine(line) {
  const values = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (ch === '"') {
      if (inQuotes && line[i + 1] === '"') { current += '"'; i += 1; }
      else { inQuotes = !inQuotes; }
    } else if (ch === ',' && !inQuotes) { values.push(current); current = ''; }
    else { current += ch; }
  }
  values.push(current);
  return values.map((v) => v.startsWith('"') && v.endsWith('"') ? v.slice(1, -1).replace(/""/g, '"') : v);
}

function csvEscape(value) {
  const normalized = value == null ? '' : String(value);
  if (/[",\n\r]/.test(normalized)) return `"${normalized.replace(/"/g, '""')}"`;
  return normalized;
}

function csvLine(values) {
  return values.map(csvEscape).join(',');
}

